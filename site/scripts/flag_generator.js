const HEX="0123456789abcdef";
const HEIGHT=5040;
const WIDTH=(HEIGHT*4)/3;
const CREATOR="Fiaguhop137";
function draw(){
    const text=document.getElementById("code").value.trim().toLowerCase();
    if(!text){
        document.getElementById("flagContainer").innerHTML="";
        return;
    }
    const circle=text.includes("o");
    let svg="";
    let finalCode="";
    if(circle){
        const parts=text.split("o",2);
        const top_text=parts[0]||"";
        const bottom_text=parts[1]||"";
        let top_code="";
        for(let c of top_text){if(HEX.includes(c))top_code+=c;}
        let bottom_code="";
        for(let c of bottom_text){if(HEX.includes(c))bottom_code+=c;}
        finalCode=top_code+"o"+bottom_code;
        const top_colors=[];
        for(let i=0;i<top_code.length;i+=6){top_colors.push(top_code.substring(i,i+6));}
        const bottom_colors=[];
        for(let i=0;i<bottom_code.length;i+=6){bottom_colors.push(bottom_code.substring(i,i+6));}
        let size=HEIGHT;
        let center=size/2;
        let radius=center;
        svg+=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="100%" height="100%">\n<!-- Generated using ${CREATOR}'s flag generator. The code used to generate this flag was ${finalCode} -->\n<defs>\n<clipPath id="top"><rect x="0" y="0" width="${size}" height="${center}"/></clipPath>\n<clipPath id="bottom"><rect x="0" y="${center}" width="${size}" height="${center}"/></clipPath>\n</defs>\n`;
        svg+=`<g clip-path="url(#top)">\n`;
        const top_count=top_colors.length;
        const top_ring_width=radius/(top_count||1);
        for(let i=0;i<top_count;i++){
            const ring_radius=radius-(i*top_ring_width);
            svg+=`<circle cx="${center}" cy="${center}" r="${ring_radius}" fill="#${top_colors[i]}"/>\n`;
        }
        svg+=`</g>\n`;
        svg+=`<g clip-path="url(#bottom)">\n`;
        const bottom_count=bottom_colors.length;
        const bottom_ring_width=radius/(bottom_count||1);
        for(let i=0;i<bottom_count;i++){
            const ring_radius=radius-(i*bottom_ring_width);
            svg+=`<circle cx="${center}" cy="${center}" r="${ring_radius}" fill="#${bottom_colors[i]}"/>\n`;
        }
        svg+=`</g>\n`;
        svg+=`</svg>`;
    }else{
        let base_text=text;
        let chevron_text="";
        const chevron=text.includes(">");
        if(chevron){
            const idx=text.indexOf(">");
            base_text=text.substring(0,idx);
            chevron_text=text.substring(idx+1);
        }
        let base_code="";
        for(let c of base_text.toLowerCase()){if(HEX.includes(c))base_code+=c;}
        let chevron_code="";
        for(let c of chevron_text.toLowerCase()){if(HEX.includes(c))chevron_code+=c;}
        finalCode=base_code+(chevron?">"+chevron_code:"");
        const colors=[];
        for(let i=0;i<=base_code.length-6;i+=6){
            const color=base_code.substring(i,i+6);
            if(colors.length>0&&colors[colors.length-1].color===color){colors[colors.length-1].count+=1;}
            else{colors.push({color:color,count:1});}
        }
        if(colors.length===0){return};
        const chevron_colors=[];
        for(let i=0;i<=chevron_code.length-6;i+=6){chevron_colors.push(chevron_code.substring(i,i+6));}
        const total_stripes=Math.floor(base_code.length/6);
        svg+=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" width="100%" height="100%">\n`;
        svg+=`<!-- Generated by ${document.getElementById("userName").value.trim()||"anonymous"} using ${CREATOR}'s flag generator. The code used to generate this flag was ${finalCode} -->\n`;
        let y=0;
        for(let i=0;i<colors.length;i++){
            let h=0;
            if(i===colors.length-1){h=HEIGHT-y;}
            else{h=(colors[i].count/total_stripes)*HEIGHT;}
            svg+=`<rect x="0" y="${y}" width="${WIDTH}" height="${h}" fill="#${colors[i].color}"/>\n`;
            y+=h;
        }
        const chevron_count=chevron_colors.length;
        if (chevron_count>0){
            const triangle_inset=HEIGHT/(2*chevron_count);
            for(let i=0;i<chevron_count;i++){
                const inset=i*triangle_inset;
                const tip=(HEIGHT/2)-inset;
                svg+=`<polygon points="0,${inset} ${tip},${HEIGHT/2} 0,${HEIGHT-inset}" fill="#${chevron_colors[i]}"/>\n`;
            }
        }
        svg+=`</svg>`;
    }
    document.getElementById("flagContainer").innerHTML=svg;
}
function download(){
    const svgContent=document.getElementById("flagContainer").innerHTML;
    if(!svgContent.trim()){return};
    let flagName=document.getElementById("flagName").value.trim()||"flag";
    if (!flagName.endsWith(".svg")){flagName+=".svg";}
    const blob=new Blob([svgContent],{type:"image/svg+xml;charset=utf-8"});
    const url=URL.createObjectURL(blob);
    const link=document.createElement("a");
    link.href=url;
    link.download=flagName;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
}